const SKIP_DIRS = ['node_modules', '.git', 'dist', 'build', '.next', 'coverage', 'vendor', '__pycache__'];
const SKIP_FILE = /(^|\/)(\.env(\.[a-z]+)?|id_(rsa|ed25519)|[^/]*\.(pem|key|p12|pfx))$/i;
const MAX_FILE = 512 * 1024;

async function filesToSources(fileList, opts = {}) {
  const sources = [];
  const skipped = [];
  for (const file of fileList) {
    const rel = (file.webkitRelativePath || file.name).replace(/^[^/]+\//, opts.stripRoot ? '' : '');
    const path = rel || file.name;
    if (SKIP_DIRS.some((d) => path.split('/').includes(d))) { skipped.push({ path, reason: 'excluded directory' }); continue; }
    if (SKIP_FILE.test(path)) { skipped.push({ path, reason: 'skipped by policy (secret-bearing file)' }); continue; }
    if (file.size > MAX_FILE) { skipped.push({ path, reason: 'larger than 512 KB' }); continue; }
    const content = await file.text();
    if (content.includes('\u0000')) { skipped.push({ path, reason: 'binary content' }); continue; }
    sources.push({ path, content });
  }
  return { sources, skipped };
}

async function inspectFiles(fileList, opts) {
  const { sources, skipped } = await filesToSources(fileList, opts);
  if (!sources.length) throw new Error('No readable text files were selected.');
  const report = inspectProject({ sources, options: { workspace: 'session://upload', agentId: 'autoclaw' } });
  report.meta.skipped = skipped;
  setReport(report, `Uploaded files (${sources.length} read, ${skipped.length} skipped)`);
}

