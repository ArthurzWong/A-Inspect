function traceRows() {
  const g = state.report.graphs.actionGraph;
  const nodes = g.nodes;
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const children = new Map();
  for (const e of g.edges) {
    if (e.kind === 'sequence') continue;
    if (!children.has(e.from)) children.set(e.from, []);
    children.get(e.from).push(e);
  }
  const depth = new Map();
  const walk = (id, d) => {
    if (depth.has(id) && depth.get(id) <= d) return;
    depth.set(id, d);
    for (const e of children.get(id) ?? []) walk(e.to, d + 1);
  };
  for (const r of g.roots) walk(r, 0);
  for (const n of nodes) if (!depth.has(n.id)) depth.set(n.id, 0);

  return nodes
    .map((n) => ({ node: n, depth: depth.get(n.id) ?? 0, edgeKinds: g.edges.filter((e) => e.to === n.id).map((e) => e.kind) }))
    .sort((a, b) => (a.depth - b.depth) || ((a.node.file ?? '').localeCompare(b.node.file ?? '')) || ((a.node.line ?? 0) - (b.node.line ?? 0)));
}

function renderTrace() {
  const tree = $('#trace-tree');
  const detail = $('#trace-detail');
  if (!tree) return;

  if (!state.report) {
    tree.innerHTML = '<li class="empty">Run an inspection first.</li>';
    detail.innerHTML = '<p class="empty">Select an action to see its evidence.</p>';
    return;
  }

  const filter = state.filter.toLowerCase();
  const rows = traceRows().filter(({ node }) => {
    if (state.onlyRisk && node.severity === 0) return false;
    if (!filter) return true;
    return `${node.label} ${node.file ?? ''} ${node.rules.join(' ')} ${node.capabilities.join(' ')}`.toLowerCase().includes(filter);
  });

  tree.innerHTML = rows.map(({ node, depth, edgeKinds }) => {
    const cls = statusClass(node.status);
    const kindChip = node.origin === 'code'
      ? '<span class="chip code">code</span>'
      : edgeKinds.includes('downstream') ? '<span class="chip downstream">downstream</span>' : '';
    const evChip = node.evidenceType === 'observed'
      ? '<span class="chip observed">observed</span>'
      : node.evidenceType === 'inferred' ? '<span class="chip inferred">inferred</span>' : '<span class="chip unknown">unknown</span>';
    return `
      <li style="margin-left:${depth * 16}px">
        <button class="node ${state.selectedAction === node.id ? 'is-active' : ''}" data-action="${esc(node.id)}">
          <span class="dot ${cls}" title="${esc(node.severityLabel)}"></span>
          <span class="node-code">${esc(node.label)}</span>
          ${kindChip}${evChip}
          <span style="flex:1"></span>
          <span class="node-file">${esc(node.file ?? '—')}${node.line ? `:${node.line}` : ''}</span>
        </button>
      </li>`;
  }).join('') || '<li class="empty">No actions match the filter.</li>';

  $$('.node', tree).forEach((btn) => {
    btn.addEventListener('click', () => {
      state.selectedAction = btn.dataset.action;
      renderTrace();
    });
  });

  renderTraceDetail();
}

