function wireInputs() {
  $$('.itab').forEach((tab) => tab.addEventListener('click', () => {
    $$('.itab').forEach((t) => t.classList.toggle('is-active', t === tab));
    $$('.input-pane').forEach((p) => p.classList.toggle('is-active', p.id === `pane-${tab.dataset.input}`));
  }));

  $$('.screen-tab').forEach((tab) => tab.addEventListener('click', () => showScreen(tab.dataset.screen)));

  const error = $('#input-error');
  const fail = (msg) => { error.textContent = msg; error.hidden = false; };
  const clearError = () => { error.hidden = true; };

  $('#inspect-btn').addEventListener('click', async () => {
    clearError();
    const active = $('.itab.is-active')?.dataset.input;
    try {
      if (active === 'paste') {
        const text = $('#cmd-input').value.trim();
        if (!text) return fail('Enter a command first.');
        runCommandInspection(text);
      } else if (active === 'script') {
        const files = $('#file-input').files;
        if (!files?.length) return fail('Select one or more files.');
        await inspectFiles(files, { stripRoot: false });
      } else if (active === 'project') {
        const files = $('#dir-input').files;
        if (!files?.length) return fail('Select a project directory.');
        await inspectFiles(files, { stripRoot: true });
      } else if (active === 'json') {
        const file = $('#json-input').files?.[0];
        if (!file) return fail('Select an inspection JSON file.');
        const parsed = JSON.parse(await file.text());
        setReport(parsed, `Loaded report: ${file.name}`);
      } else if (active === 'fixture') {
        await loadFixture();
      } else if (active === 'github') {
        return fail('Repository fetching runs through the CLI for safety. Copy the command shown in the plan above.');
      }
    } catch (err) {
      fail(String(err?.message ?? err));
    }
  });

  $('#sandbox-btn').disabled = false;
  $('#sandbox-btn').addEventListener('click', async () => {
    const provider = createSandboxProvider({ provider: 'plan' });
    const { handle } = await provider.create({ workspace: '<workspace>', image: 'node:22-alpine' });
    const result = await provider.execute(handle, 'node bin/contentpulse.js run --config sources.yaml');
    window.alert(
      'Sandbox plan (nothing executed)\n\n'
      + `docker ${(result.container ?? []).join(' ')}\n\n`
      + 'Why nothing ran:\n'
      + '• the default provider refuses execution (fail closed);\n'
      + `• ${SANDBOX_LIMITATIONS[0]}\n\n`
      + 'Minimum required controls:\n'
      + SANDBOX_MINIMUM_REQUIREMENTS.map((r) => `• ${r.label}`).join('\n'),
    );
  });

  $('#load-fixture').addEventListener('click', () => {
    clearError();
    loadFixture().catch((err) => fail(String(err?.message ?? err)));
  });
  $('#load-real').addEventListener('click', () => {
    clearError();
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = '.json,application/json';
    input.addEventListener('change', async () => {
      const file = input.files?.[0];
      if (!file) return;
      try {
        setReport(JSON.parse(await file.text()), `Local report: ${file.name}`);
      } catch (err) { fail(`Could not read report: ${err.message}`); }
    });
    input.click();
  });

  $('#gh-input').addEventListener('input', (e) => {
    const plan = planRepositoryInspection(e.target.value);
    const box = $('#gh-plan');
    if (!plan.ok) { box.innerHTML = ''; return; }
    box.innerHTML = `
      <div class="kv">
        <dt>Permissions</dt><dd>${esc(Object.entries(GITHUB_APP_PERMISSIONS).map(([k, v]) => `${k}:${v}`).join(', '))}</dd>
        <dt>Steps</dt><dd>${esc(GITHUB_INSPECTION_WORKFLOW.join(' → '))}</dd>
        <dt>Later</dt><dd>${esc(GITHUB_LATER.join(' · '))}</dd>
        <dt>Run</dt><dd>npm run inspect -- --github ${esc(plan.repo.owner)}/${esc(plan.repo.repo)} --format json --out report.json</dd>
      </div>
      <p class="note" style="margin-top:8px">${esc(plan.guardrails[0])} ${esc(plan.guardrails[1])}</p>`;
  });

  $('#trace-filter').addEventListener('input', (e) => { state.filter = e.target.value; renderTrace(); });
  $('#trace-only-risk').addEventListener('change', (e) => { state.onlyRisk = e.target.checked; renderTrace(); });

  $('#audit-verify').addEventListener('click', () => {
    state.tamperedEvents = null;
    state.auditVerdict = state.auditLog.verify();
    renderGate();
  });

  $('#audit-tamper').addEventListener('click', () => {
    // Educational demonstration on an in-memory copy. The real ledger is not
    // modified: this exists so the tamper-evidence claim is checkable.
    const copy = state.auditLog.events().map((e) => JSON.parse(JSON.stringify(e)));
    if (copy.length < 2) {
      window.alert('Not enough events to demonstrate tampering. Record a decision first.');
      return;
    }
    const target = copy[Math.max(0, copy.length - 2)];
    target.payload = { ...target.payload, tampered: 'an attacker edited this event after the fact' };
    const testLog = createAuditLog({ workspaceId: 'tamper-demo', agentId: 'autoclaw' });
    testLog.load({ events: copy });
    state.tamperedEvents = target.seq;
    state.auditVerdict = testLog.verify();
    renderGate();
  });
}

function loadFixture() {
  return getFixtureSources().then((sources) => {
    if (!sources.length) throw new Error('The fixture is empty. Run: npm run build:web');
    const report = inspectProject({
      sources,
      options: { workspace: 'fixture://contentpulse-demo', agentId: 'autoclaw' },
    });
    report.meta.fixture = FIXTURE_LABEL;
    setReport(report, FIXTURE_LABEL);
  });
}

