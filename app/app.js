function auditEvents() {
  return state.auditLog ? state.auditLog.events() : [];
}

function currentAuditVerification() {
  if (!state.auditLog) return { valid: true, reason: 'no ledger', brokenAt: null };
  return state.auditLog.verify();
}

function pendingDecisions() {
  if (!state.report) return [];
  return state.report.decisions.filter((d) => ['REQUIRE_APPROVAL', 'SANDBOX_ONLY', 'DENY'].includes(d.decision));
}

function renderGate() {
  const list = $('#gate-list');
  const table = $('#audit-table');
  const verdict = $('#audit-verdict');
  if (!list) return;

  if (!state.report) {
    list.innerHTML = '<p class="empty">Run an inspection first.</p>';
    table.innerHTML = '';
    verdict.textContent = '';
    return;
  }

  const items = pendingDecisions();
  list.innerHTML = items.length ? items.map((d) => {
    const handled = state.decisions[d.actionId];
    const cls = d.decision === 'DENY' ? 'deny' : d.decision === 'SANDBOX_ONLY' ? 'req' : 'req';
    const caps = (d.capabilities ?? []).map((c) => `<span class="chip">${esc(c)}</span>`).join('') || '<span class="chip">none recorded</span>';
    const unique = new Set((d.capabilities ?? []).map((c) => c.split('.')[0]));
    return `
      <div class="gate-item" id="gate-${esc(d.actionId)}">
        <h4>${esc(d.request.command)} ${esc((d.request.arguments ?? []).join(' '))}</h4>
        <p class="note">agent ${esc(d.request.agent_id)} · ${esc(d.request.action_type)} · ${esc(d.request.working_directory)}</p>
        <div class="gate-caps">${caps}</div>
        <div class="verdict-line ${cls}">policy result: ${esc(d.decision)}${d.approvalId ? ` · ${esc(d.approvalId)}` : ''}</div>
        <ul class="reasons">${d.reasons.slice(0, 4).map((r) => `<li>${esc(r)}</li>`).join('')}</ul>
        ${handled
          ? `<p class="note" style="margin-top:10px">Handled: <strong>${esc(handled.label)}</strong> at ${esc(handled.at)}</p>`
          : `<div class="row-btns">
              ${APPROVAL_ACTIONS.map((a) => `<button class="btn ${a.id === 'deny' ? 'btn-danger' : a.id.startsWith('allow') ? 'btn-ok' : 'btn-ghost'}"
                 data-approve="${esc(a.id)}" data-action-id="${esc(d.actionId)}"
                 title="${esc(a.effect)}">${esc(a.label)}</button>`).join('')}
             </div>
             <p class="note" style="margin-top:8px">There is deliberately no "allow everything" option. The blocked variants are: ${esc(FORBIDDEN_APPROVAL_ACTIONS.join(', '))}</p>`}
      </div>`;
  }).join('') : '<p class="empty">Nothing is waiting for approval.</p>';

  $$('[data-approve]', list).forEach((btn) => btn.addEventListener('click', () => handleApproval(btn.dataset.actionId, btn.dataset.approve)));

  /* audit table */
  const events = auditEvents();
  table.innerHTML = `
    <thead><tr><th>seq</th><th>type</th><th>timestamp</th><th>hash</th><th>previous</th></tr></thead>
    <tbody>${events.map((e) => `
      <tr class="${state.auditVerdict && state.auditVerdict.brokenAt === e.seq ? 'bad' : ''}">
        <td>${esc(e.seq)}</td><td>${esc(e.type)}</td><td>${esc(e.timestamp)}</td>
        <td class="hash">${esc(shortHash(e.hash))}</td><td class="hash">${esc(shortHash(e.previous_hash))}</td>
      </tr>`).join('')}</tbody>`;

  if (state.tamperedEvents) {
    const v = state.auditVerdict;
    verdict.className = 'verdict bad';
    verdict.textContent = `simulated tamper detected at event ${v.brokenAt}: ${v.reason}`;
  } else if (state.auditVerdict) {
    verdict.className = `verdict ${state.auditVerdict.valid ? 'ok' : 'bad'}`;
    verdict.textContent = state.auditVerdict.valid
      ? `chain intact · ${events.length} events · head ${shortHash(state.auditLog.head())}`
      : `chain broken at ${state.auditVerdict.brokenAt}: ${state.auditVerdict.reason}`;
  } else {
    verdict.className = 'verdict';
    verdict.textContent = `${events.length} events recorded. Verify to recompute the chain.`;
  }
}

function handleApproval(actionId, approvalId) {
  const action = APPROVAL_ACTIONS.find((a) => a.id === approvalId);
  const decision = state.report.decisions.find((d) => d.actionId === actionId);
  if (!action || !decision) return;

  if (action.id === 'inspect-deeper') {
    const node = state.report.graphs.actionGraph.nodes.find((n) => n.id === actionId);
    const reached = node?.downstreamFiles ?? [];
    window.alert(reached.length
      ? `Already inspected downstream: ${reached.join(', ')}\n\nRe-analysis uses the same deterministic rules, so no new conclusions appear without new files.`
      : 'No downstream files were reachable from this action in the inspected set. That is an unknown, not a clean result.');
    return;
  }

  if (action.id === 'deny') {
    state.auditLog.append(EVENT.ACTION_DENIED, {
      action: decision.request.command, arguments: decision.request.arguments,
      decision: 'DENY', operator: 'user', result: 'denied', policy: decision.policyId,
    });
  } else if (action.decision === 'SANDBOX_ONLY') {
    state.auditLog.append(EVENT.ACTION_APPROVED, {
      action: decision.request.command, arguments: decision.request.arguments,
      decision: 'SANDBOX_ONLY', operator: 'user', result: 'approved-in-sandbox',
      execution_environment: 'sandbox', policy: decision.policyId,
    });
    state.auditLog.append(EVENT.SANDBOX_STARTED, { provider: 'docker (hardened)', network: 'none', note: 'plan recorded; no provider is configured in this session, so nothing executed' });
  } else {
    state.auditLog.append(EVENT.ACTION_APPROVED, {
      action: decision.request.command, arguments: decision.request.arguments,
      decision: action.id === 'allow-once' ? 'ALLOW' : 'ALLOW_WITH_LOG',
      scope: action.id === 'allow-project' ? 'project' : 'once',
      operator: 'user', result: 'approved', policy: decision.policyId,
    });
  }

  state.decisions[actionId] = {
    label: action.label,
    at: new Date().toISOString(),
  };
  state.auditVerdict = null;
  renderAll();
}

