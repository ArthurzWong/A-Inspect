function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function shortHash(h) {
  return h ? `${h.slice(0, 10)}…${h.slice(-6)}` : '—';
}

function statusClass(status) {
  return ['red', 'orange', 'yellow', 'green', 'grey'].includes(status) ? status : 'grey';
}

